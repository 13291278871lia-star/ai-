#!/usr/bin/env python3
"""Build the internal-learning video catalogue from the local folder structure."""

from __future__ import annotations

import json
import re
from pathlib import Path


PROJECT = Path(__file__).resolve().parents[1]
ROOT = PROJECT / "assets/training/masters/videos"
OUTPUT = PROJECT / "src/training-video-data.js"


def natural_key(value: str) -> list[object]:
    return [int(part) if part.isdigit() else part.casefold() for part in re.split(r"(\d+)", value)]


def video_key(item: dict) -> tuple[int, list[object]]:
    match = re.search(r"ep\s*0*(\d+)", item["title"], re.I)
    return (int(match.group(1)) if match else 9999, natural_key(item["title"]))


def display_title(relative: Path) -> str:
    stem = relative.stem.strip()
    if relative.parts[0] == "敗部復活":
        match = re.search(r"ep\s*0*(\d+).*?(\d+)\s*[:/]\s*(\d+)", stem, re.I)
        if match:
            episode, part, total = (int(value) for value in match.groups())
            return f"敗部復活 ep{episode:02d} {part}/{total}.mp4"
        return re.sub(r"^败部复活[.\s]*", "敗部復活 ", stem, flags=re.I).replace(":", "/")
    return stem.replace(":", "/")


def group_details(relative: Path) -> tuple[str, str, str]:
    parts = relative.parts
    if parts[0] == "敗部復活":
        return "revival", "敗部復活", "按集數及分段整理的實戰分享課程"
    if parts[0] == "新人起動":
        return "new-start", "新人起動／舊人翻撻", "新人入門及重新起動系列課程"
    return parts[0], parts[0], "內部分享課程"


def main() -> None:
    groups: dict[str, dict] = {}
    for video in ROOT.rglob("*.mp4"):
        relative = video.relative_to(ROOT)
        key, title, subtitle = group_details(relative)
        group = groups.setdefault(key, {"title": title, "subtitle": subtitle, "videos": []})
        group["videos"].append({
            "title": display_title(relative),
            "src": f"assets/training/masters/videos/{relative.as_posix()}",
        })

    series = list(groups.values())
    order = {"敗部復活": 0, "新人起動／舊人翻撻": 1}
    series.sort(key=lambda item: (order.get(item["title"], 2), natural_key(item["title"])))
    for group in series:
        group["videos"].sort(key=video_key)

    payload = json.dumps(series, ensure_ascii=False, indent=2)
    OUTPUT.write_text(
        "/* Auto-generated by scripts/sync_training_catalog.py. */\n"
        f"export const masterVideoSeries = {payload};\n",
        encoding="utf-8",
    )
    print(f"Wrote {sum(len(item['videos']) for item in series)} videos in {len(series)} series to {OUTPUT}")


if __name__ == "__main__":
    main()
